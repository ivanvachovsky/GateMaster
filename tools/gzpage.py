#!/usr/bin/env python3
"""Gzips firmware/web/index.html into firmware/GateMaster/webpage_gz.h (the page is stored in the firmware)."""
import gzip, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "firmware/web/index.html").read_bytes()
gz = gzip.compress(html, compresslevel=9, mtime=0)
lines = [", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
out = ["// Generated by tools/gzpage.py from firmware/web/index.html - do not edit", "#pragma once", "#include <Arduino.h>",
       f"// {len(html)} bytes, {len(gz)} gzipped", "static const uint8_t WEBPAGE_GZ[] PROGMEM = {", ",\n".join(lines), "};"]
(root / "firmware/GateMaster/webpage_gz.h").write_text("\n".join(out) + "\n")
print(f"web page: {len(html)} bytes -> {len(gz)} gzipped")
