#!/usr/bin/env python3
"""Writes firmware/GateMaster/ca_certs.h: root certificates the board trusts for the update check
(GitHub Pages). Several roots, so a change of certificate authority by GitHub does not break updates."""
import pathlib, sys
ROOTS = ["USERTrust_RSA_Certification_Authority", "Sectigo_Public_Server_Authentication_Root_R46",
         "DigiCert_Global_Root_G2", "ISRG_Root_X1", "GTS_Root_R1"]
src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs")
out = ['// Generated by tools/make_certs.py - root CAs for HTTPS to ivanvachovsky.github.io', '#pragma once',
       'static const char CA_CERTS[] =']
for r in ROOTS:
    pem = (src / f"{r}.pem").read_text().strip()
    out.append(f'  // {r}')
    out += [f'  "{line}\\n"' for line in pem.splitlines()]
out.append(';')
p = pathlib.Path(__file__).resolve().parent.parent / "firmware/GateMaster/ca_certs.h"
p.write_text("\n".join(out) + "\n")
print(p, len(ROOTS), "roots")
